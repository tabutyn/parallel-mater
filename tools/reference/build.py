#!/usr/bin/env python3
"""Generate the C contract and consumer-facing API reference."""
import argparse
import json
from pathlib import Path
import re

from content import PRELUDE, SECTIONS, STRUCTURE_TYPES
from provenance import ROOT, file_sha256, registry_provenance
from runtime_coverage import generate_coverage

DEST = ROOT / "docs/reference"
INCLUDE_DEST = ROOT / "include/parallel_mater"
RELEASE_ARTIFACTS = (
    "docs/reference/api/parallel_mater.h",
    "docs/reference/api/interop_vulkan.h",
    "include/parallel_mater/parallel_mater.h",
    "include/parallel_mater/interop_vulkan.h",
    "docs/reference/api-coverage.json",
    "docs/reference/parallel-mater-specification.md",
    "docs/reference/parallel-mater-specification.pdf",
    "docs/reference/parallel-mater-specification.layout.json",
    "docs/reference/parallel-mater-reference.pdf",
    "docs/reference/parallel-mater-reference.layout.json",
)


def all_cards():
    return [card for section in SECTIONS for card in section.cards]


def render_headers(destination=DEST, include_destination=INCLUDE_DEST):
    cards = all_cards()
    notice = ("/* GENERATED by tools/reference/build.py from registry/pm.xml.\n"
              f" * Registry SHA-256: {registry_provenance()['sha256']}\n"
              " * Parallel Mater 0.3 command API.\n"
              " * See docs/reference/README.md and MIGRATION.md. */\n")
    closing = '\n#ifdef __cplusplus\n}\n#endif\n#endif\n'
    rendered = []
    for extension, filename in ((False, "parallel_mater.h"), (True, "interop_vulkan.h")):
        prelude = ("#ifndef PARALLEL_MATER_INTEROP_VULKAN_H\n#define PARALLEL_MATER_INTEROP_VULKAN_H\n"
                   '#include "parallel_mater.h"\n#include <vulkan/vulkan.h>\n'
                   '#ifdef __cplusplus\nextern "C" {\n#endif\n') if extension else PRELUDE.strip() + "\n" + STRUCTURE_TYPES + "\n"
        selected = [c for c in cards if c.extension == extension and c.emit_header]
        definitions = "\n\n".join(c.types for c in selected if c.types)
        functions = "\n\n".join(c.functions for c in selected if c.functions)
        signatures = re.findall(r"^(\w+) (pm\w+)\((.*?)\);", functions, re.M | re.S)
        pointers = "\n\n".join(f"typedef {result} (PMAPI_CALL *PFN_{name})({args});"
                                 for result, name, args in signatures)
        functions = re.sub(r"^(\w+) (pm\w+)\(", r"PMAPI_ATTR \1 PMAPI_CALL \2(", functions, flags=re.M)
        target = destination / "api" / filename
        installed = include_destination / (
            "interop_vulkan.h" if extension else "parallel_mater.h")
        rendered.append((target, installed,
                         notice + prelude + "\n" + definitions + "\n\n" +
                         pointers + "\n\n" + functions + closing))
    return rendered


def generate_headers(check=False, destination=DEST, include_destination=INCLUDE_DEST):
    paths = []
    stale = []
    for target, installed, output in render_headers(destination, include_destination):
        paths.append(target)
        if check:
            for path in (target, installed):
                if not path.exists() or path.read_text(encoding="utf-8") != output:
                    stale.append(str(path.relative_to(ROOT)))
            continue
        for path in (target, installed):
            if not path.exists() or path.read_text(encoding="utf-8") != output:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(output, encoding="utf-8", newline="\n")
    if stale:
        raise RuntimeError(
            "generated API files are stale; run "
            "'python3 tools/reference/build.py --headers-only': " +
            ", ".join(stale))
    return paths


def write_release_manifest(artifact_root, provenance, toolchain):
    artifacts = {}
    for relative in RELEASE_ARTIFACTS:
        path = artifact_root / relative
        artifacts[relative] = {
            "sha256": file_sha256(path),
            "size": path.stat().st_size,
        }
    manifest = {
        "schema": "parallel-mater-reference-artifacts/v1",
        "registry": provenance,
        "toolchain": {key: value for key, value in toolchain.items() if key != "font_dir"},
        "artifacts": artifacts,
        "known_nondeterminism": [],
    }
    output = artifact_root / "docs/reference/release-artifacts.json"
    output.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    return output



def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-dir", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--artifact-root", type=Path, default=ROOT,
                        help="Write the complete generated set below this staging root")
    parser.add_argument("--headers-only", action="store_true",
                        help="Regenerate headers and API coverage without PDF dependencies")
    parser.add_argument("--check-generated", action="store_true",
                        help="Fail if checked-in public headers differ from the registry")
    parser.add_argument("--text-only", action="store_true",
                        help="Regenerate headers, coverage and searchable spec without PDF packages")
    args = parser.parse_args()
    artifact_root = args.artifact_root.resolve()
    destination = artifact_root / "docs/reference"
    include_destination = artifact_root / "include/parallel_mater"
    output = args.output or destination / "parallel-mater-reference.pdf"
    provenance = registry_provenance()
    generate_headers(check=args.check_generated, destination=destination,
                     include_destination=include_destination)
    if args.check_generated:
        from specification_text import render_markdown
        if (destination / "parallel-mater-specification.md").read_text(encoding="utf-8") != render_markdown():
            raise RuntimeError("specification text is stale; run tools/reference/build.py --text-only")
        print("PASS: public headers and specification text match canonical sources")
        return
    destination.mkdir(parents=True, exist_ok=True)
    generate_coverage(ROOT, destination, provenance)
    if args.text_only:
        from specification_text import render_markdown
        (destination / "parallel-mater-specification.md").write_text(
            render_markdown(), encoding="utf-8", newline="\n")
        print("Built public headers, coverage and specification text")
        return
    if args.headers_only:
        print("Built public headers and runtime API coverage")
        return
    from layout import build_pdf, register_fonts
    from specification import build_specification
    from toolchain import DEFAULT_FONT_DIR, verify_environment
    toolchain = verify_environment(args.font_dir or DEFAULT_FONT_DIR)
    register_fonts(toolchain["font_dir"])
    output.parent.mkdir(parents=True, exist_ok=True)
    spec_output = output.with_name("parallel-mater-specification.pdf")
    specification = build_specification(spec_output)
    specification["registry"] = provenance
    spec_output.with_suffix(".layout.json").write_text(
        json.dumps(specification, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8", newline="\n")
    manifest = build_pdf(output, specification)
    manifest["registry"] = provenance
    output.with_suffix(".layout.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8", newline="\n")
    if output.resolve() == (destination / "parallel-mater-reference.pdf").resolve():
        write_release_manifest(artifact_root, provenance, toolchain)
    print(f"Built {output}: {manifest['page_count']} pages, "
          f"{len(manifest['symbols'])} indexed symbols, "
          f"{manifest['columns']} columns")
    print(f"Built {spec_output}: {specification['page_count']} pages")


if __name__ == "__main__":
    main()
