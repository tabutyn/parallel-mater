#!/usr/bin/env python3
"""Generate the C contract and consumer-facing API reference."""
import argparse
import json
from pathlib import Path
import re

from content import PRELUDE, SECTIONS, STRUCTURE_TYPES
from runtime_coverage import generate_coverage

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "docs/reference"


def all_cards():
    return [card for section in SECTIONS for card in section.cards]


def render_headers():
    cards = all_cards()
    notice = ("/* GENERATED by tools/reference/build.py from registry/pm.xml.\n"
              " * Parallel Mater 0.2 command API.\n"
              " * See docs/reference/README.md and MIGRATION.md. */\n")
    closing = '\n#ifdef __cplusplus\n}\n#endif\n#endif\n'
    rendered = []
    for extension, filename in ((False, "parallel_mater.h"), (True, "interop_vulkan.h")):
        prelude = ("#ifndef PARALLEL_MATER_INTEROP_VULKAN_H\n#define PARALLEL_MATER_INTEROP_VULKAN_H\n"
                   '#include "parallel_mater.h"\n#include <vulkan/vulkan.h>\n'
                   '#ifdef __cplusplus\nextern "C" {\n#endif\n') if extension else PRELUDE.strip() + "\n" + STRUCTURE_TYPES + "\n"
        selected = [c for c in cards if c.extension == extension and c.emit_header]
        definitions = "\n\n".join(c.types for c in selected if c.types)
        functions = "\n\n".join(c.functions for c in selected if c.functions)
        signatures = re.findall(r"^(\w+) (pm\w+)\((.*?)\);", functions, re.M | re.S)
        pointers = "\n\n".join(f"typedef {result} (PMAPI_CALL *PFN_{name})({args});"
                                 for result, name, args in signatures)
        functions = re.sub(r"^(\w+) (pm\w+)\(", r"PMAPI_ATTR \1 PMAPI_CALL \2(", functions, flags=re.M)
        target = DEST / "api" / filename
        installed = ROOT / "include/parallel_mater" / (
            "interop_vulkan.h" if extension else "parallel_mater.h")
        rendered.append((target, installed,
                         notice + prelude + "\n" + definitions + "\n\n" +
                         pointers + "\n\n" + functions + closing))
    return rendered


def generate_headers(check=False):
    paths = []
    stale = []
    for target, installed, output in render_headers():
        paths.append(target)
        if check:
            for path in (target, installed):
                if not path.exists() or path.read_text(encoding="utf-8") != output:
                    stale.append(str(path.relative_to(ROOT)))
            continue
        for path in (target, installed):
            if not path.exists() or path.read_text(encoding="utf-8") != output:
                path.write_text(output, encoding="utf-8")
    if stale:
        raise RuntimeError(
            "generated API files are stale; run "
            "'python3 tools/reference/build.py --headers-only': " +
            ", ".join(stale))
    return paths



def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-dir", type=Path)
    parser.add_argument("--output", type=Path, default=DEST / "parallel-mater-reference.pdf")
    parser.add_argument("--headers-only", action="store_true",
                        help="Regenerate headers and API coverage without PDF dependencies")
    parser.add_argument("--check-generated", action="store_true",
                        help="Fail if checked-in public headers differ from the registry")
    parser.add_argument("--text-only", action="store_true",
                        help="Regenerate headers, coverage and searchable spec without PDF packages")
    args = parser.parse_args()
    generate_headers(check=args.check_generated)
    if args.check_generated:
        from specification_text import render_markdown
        if (DEST / "parallel-mater-specification.md").read_text(encoding="utf-8") != render_markdown():
            raise RuntimeError("specification text is stale; run tools/reference/build.py --text-only")
        print("PASS: public headers and specification text match canonical sources")
        return
    generate_coverage(ROOT, DEST)
    if args.text_only:
        from specification_text import render_markdown
        (DEST / "parallel-mater-specification.md").write_text(render_markdown(), encoding="utf-8")
        print("Built public headers, coverage and specification text")
        return
    if args.headers_only:
        print("Built public headers and runtime API coverage")
        return
    from layout import build_pdf, register_fonts
    from specification import build_specification
    register_fonts(args.font_dir)
    spec_output = args.output.with_name("parallel-mater-specification.pdf")
    specification = build_specification(spec_output)
    spec_output.with_suffix(".layout.json").write_text(
        json.dumps(specification, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    manifest = build_pdf(args.output, specification)
    args.output.with_suffix(".layout.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Built {args.output}: {manifest['page_count']} pages, "
          f"{len(manifest['symbols'])} indexed symbols, "
          f"{manifest['columns']} columns")
    print(f"Built {spec_output}: {specification['page_count']} pages")


if __name__ == "__main__":
    main()
