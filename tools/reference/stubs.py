"""Generate linkable, fail-closed placeholders for the reviewed C contract.

Policies are explicit: a newly added output parameter MUST be classified before
generation succeeds. These stubs never allocate, submit work, wait, or probe a GPU.
"""
import json

from api_model import declarations, public_types
from content import SECTIONS
from model import SPEC_NUMBERS
from check_api import legacy_inventory


# Non-const pointer arguments are otherwise singular outputs, cleared on failure.
# Array outputs require a capacity-aware policy, never an inferred memset size.
ARRAY_OUTPUTS = {
    "pmEnumeratePhysicalDevices": {"pDevices"},
    "pmGetPhysicalDeviceQueueFamilies": {"pProperties"},
    "pmAllocateCommandBuffers": {"pBuffers"},
    "pmGetQueryPoolResults": {"pData"},
}
SPECIAL = {"pmGetInstanceProcAddr", "pmGetDeviceProcAddr"}
BOOTSTRAP = ("pmGetInstanceProcAddr", "pmEnumerateInstanceVersion", "pmCreateInstance")


def output_params(command):
    return [(kind, name) for kind, name in command["params"]
            if "*" in kind and not kind.startswith("const ")]


def body(command):
    name = command["name"]
    lines = [f"    (void){arg};" for _, arg in command["params"]]
    if name == "pmGetInstanceProcAddr":
        lines.append("    if (instance != nullptr || pName == nullptr) return nullptr;")
        lines.extend(f'    if (std::strcmp(pName, "{entry}") == 0)\n'
                     f'        return reinterpret_cast<PFN_pmVoidFunction>({entry});'
                     for entry in BOOTSTRAP)
        return lines + ["    return nullptr;"]
    if name == "pmGetDeviceProcAddr":
        return lines + ["    return nullptr;"]
    array_outputs = ARRAY_OUTPUTS.get(name, set())
    for _, arg in output_params(command):
        if arg in array_outputs:
            if name == "pmAllocateCommandBuffers":
                lines += ["    if (pBuffers != nullptr)",
                          "        for (uint32_t i = 0; i < count; ++i) pBuffers[i] = nullptr;"]
            continue  # No records or result bytes are produced on failure.
        value = "PM_ERROR_FEATURE_NOT_PRESENT" if arg == "pExecutionResult" else "{}"
        lines.append(f"    if ({arg} != nullptr) *{arg} = {value};")
    if command["returns"] == "PmResult":
        required = [arg for _, arg in output_params(command) if arg not in array_outputs]
        if required:
            lines += [f"    if ({' || '.join(arg+' == nullptr' for arg in required)})",
                      "        return PM_ERROR_INVALID_ARGUMENT;"]
        if name == "pmAllocateCommandBuffers":
            lines += ["    if (count != 0 && pBuffers == nullptr)",
                      "        return PM_ERROR_INVALID_ARGUMENT;"]
        lines.append("    return PM_ERROR_FEATURE_NOT_PRESENT;")
    elif command["returns"] != "void":
        raise ValueError(f"Missing return policy for {name}")
    return lines


def generate_stubs(root, destination):
    commands = declarations()
    # Freeze the initial singular-output classification in an auditable file.
    # New/changed pointer parameters must be deliberately classified there.
    policies_path = root / "tools/reference/stub_outputs.json"
    policies = json.loads(policies_path.read_text())
    actual = {cmd["name"]: {name: kind for kind, name in output_params(cmd)}
              for cmd in commands if output_params(cmd)}
    if policies != actual:
        raise ValueError("Output parameters changed: review and update stub_outputs.json")
    generated = root / "src/command"
    generated.mkdir(parents=True, exist_ok=True)
    notice = "// GENERATED by tools/reference/build.py; edit content.py/stubs.py.\n"
    for extension, filename in ((False, "stubs.cpp"), (True, "vulkan_stubs.cpp")):
        header = "command_vulkan.h" if extension else "command.h"
        source = notice + f'#include "parallel_mater/{header}"\n#include <cstring>\n\n'
        for cmd in commands:
            if cmd["extension"] != extension:
                continue
            source += f'extern "C" PMAPI_ATTR {cmd["returns"]} PMAPI_CALL {cmd["name"]}({cmd["args"]})\n{{\n'
            source += "\n".join(body(cmd)) + "\n}\n\n"
        (generated / filename).write_text(source.rstrip() + "\n")
    inventory = {
        "contract": "Parallel Mater command API 0.2 design draft",
        "implementation": "unsupported stubs; no physics execution",
        "functions": [{"name": cmd["name"], "section": SPEC_NUMBERS[cmd["card"]],
                       "card": cmd["card"], "header": "command_vulkan.h" if cmd["extension"] else "command.h",
                       "source": "src/command/vulkan_stubs.cpp" if cmd["extension"] else "src/command/stubs.cpp",
                       "status": "bootstrap lookup" if cmd["name"] in SPECIAL else "unsupported stub"}
                      for cmd in commands],
        "types": [{"name": name, "section": SPEC_NUMBERS[card.key], "card": card.key}
                  for section in SECTIONS for card in section.cards
                  for name in sorted(public_types(card.types))],
        "derived_function_pointer_types": ["PFN_" + cmd["name"] for cmd in commands],
        "derived_type_rule": "Each PFN_pmName has pmName's exact signature and PMAPI_CALL convention; section "
                             + SPEC_NUMBERS["base_types"] + ".",
    }
    (destination / "api-coverage.json").write_text(json.dumps(inventory, indent=2) + "\n")
    (destination / "legacy-api-inventory.json").write_text(json.dumps(legacy_inventory(root), indent=2) + "\n")
