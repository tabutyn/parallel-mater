"""Generate transport bindings, never physics, from Slang's reflected ABI.

The existing typed CUDA host wrappers provide the argument order. Only their
launch syntax changes. Slang's emitted POD declarations preserve the host ABI;
SPIR-V reflection supplies constant offsets and validates storage layouts.
Unsupported syntax or layout changes fail the build instead of guessing.
"""
import argparse
import json
import pathlib
import re
import struct


def split_args(text):
    result, begin, depth = [], 0, 0
    for i, c in enumerate(text):
        if c in '(<[': depth += 1
        elif c in ')>]': depth -= 1
        elif c == ',' and depth == 0:
            result.append(text[begin:i].strip()); begin = i + 1
    result.append(text[begin:].strip())
    return result


def generate(args):
    native = pathlib.Path(args.cuda).read_text()
    native = re.sub(r'^#line.*$', '', native, flags=re.M)
    declarations = re.findall(r'^struct (\w+)\s*\{([^{}]*)\};', native, re.M)
    structs = {name: body for name, body in declarations}
    header = ['// Generated by generate_vulkan_dispatch.py; do not edit.',
              '#include "driver/vulkan/schedule_context.hpp"',
              'namespace {', 'using uint = unsigned int;',
              'using ulonglong = unsigned long long;',
              'using longlong = long long;', 'using uchar = unsigned char;',
              'using ushort = unsigned short;',
              'template<class T, unsigned N> struct FixedArray { T data[N]; };']
    header += [f'struct {name} {{{body}}};' for name, body in declarations]
    reflection = json.loads(pathlib.Path(args.reflection).read_text())
    reflected_types = {}
    def collect(value):
        if isinstance(value, dict):
            if value.get('kind') == 'struct': reflected_types[value['name']] = value
            for child in value.values(): collect(child)
        elif isinstance(value, list):
            for child in value: collect(child)
    collect(reflection)
    storage_names = set()
    def storage_types(value):
        if isinstance(value, dict):
            if value.get('kind') == 'pointer':
                def mark(t):
                    if isinstance(t, str): t = reflected_types.get(t, {})
                    if t.get('kind') == 'struct':
                        storage_names.add(t['name'])
                        for field in t['fields']: mark(field['type'])
                    elif t.get('kind') == 'array': mark(t['elementType'])
                mark(value['valueType'])
            for child in value.values(): storage_types(child)
        elif isinstance(value, list):
            for child in value: storage_types(child)
    storage_types(reflection)
    for name, body in declarations:
        shader_type = reflected_types.get(re.sub(r'_\d+$', '', name))
        if not shader_type or shader_type['name'] not in storage_names: continue
        fields = [re.search(r'(\w+)\s*$', field.strip())[1]
                  for field in body.split(';') if field.strip()]
        if len(fields) != len(shader_type['fields']):
            raise ValueError(name + ': storage fields changed')
        size = next(s['value'] for s in shader_type['sizes'] if s['kind'] == 'uniform')
        header.append(f'static_assert(sizeof({name}) == {size}U);')
        for field, reflected in zip(fields, shader_type['fields']):
            if re.sub(r'_\d+$', '', field) != reflected['name']:
                raise ValueError(name + ': field order changed')
            header.append(f'static_assert(offsetof({name}, {field}) == {reflected["binding"]["offset"]}U);')
    entries = {e['name']: e for e in reflection['entryPoints']}
    signatures = dict(re.findall(r'extern "C" __global__ void (\w+)\((.*?)\)\s*\{', native, re.S))
    shader = pathlib.Path(args.spirv).read_bytes()
    words = struct.unpack('<' + 'I' * (len(shader) // 4), shader)
    header.append('alignas(4) constexpr std::uint32_t shader_code[]{' + ','.join(hex(w) for w in words) + '};')
    for name, entry in entries.items():
        if name not in signatures:
            raise ValueError(f'{name}: no matching Slang host signature')
        parameters = split_args(signatures[name])
        reflected = [p for p in entry['parameters'] if p.get('binding', {}).get('kind') == 'uniform']
        if len(parameters) != len(reflected): raise ValueError(name + ': argument count changed')
        size = max((p['binding']['offset'] + p['binding']['size'] for p in reflected), default=4)
        names = [re.search(r'(\w+)$', p)[1] for p in parameters]
        lookup = {p['name']: n for p, n in zip(reflected, names)}
        lines = [f'void vk_{name}(cudaStream_t stream, dim3 grid, dim3 block, {signatures[name]}) {{',
                 'auto *execution = parallel_mater::vulkan::context(stream);',
                 'if (!execution) return;', f'std::array<std::byte, {(size+3)&~3}> constants{{}};']
        if name == 'pm_evaluate_rigid_leaf_pairs': lines.append('block.x = 8U;')
        def pack(p, variable, base=0):
            binding, typ = p['binding'], p['type']
            if isinstance(typ, str): typ = reflected_types[typ]
            offset, length = base + binding['offset'], binding['size']
            value = variable
            if typ['kind'] == 'struct':
                native_name = next(n for n in structs if re.sub(r'_\d+$', '', n) == typ['name'])
                native_fields = [re.search(r'(\w+)\s*$', f.strip())[1] for f in structs[native_name].split(';') if f.strip()]
                for field, native_field in zip(typ['fields'], native_fields):
                    pack(field, f'{variable}.{native_field}', offset)
                return
            elif typ['kind'] == 'pointer':
                pointee = typ['valueType']
                pointee = pointee if isinstance(pointee, str) else pointee.get('name')
                if pointee == 'TriangleMeshResource':
                    body = lookup.get('parameters', lookup.get('body_parameters'))
                    count = lookup.get('body_count', lookup.get('count'))
                    count_type = next((x['type']['kind'] for x in reflected if x['name'] == 'count'), None)
                    if 'body_count' not in lookup and count_type == 'pointer': count = None
                    if 'body_index' in lookup: count = f'({lookup["body_index"]} + 1U)'
                    if name == 'fluid_resolve_moving_contacts':
                        # The immediately preceding detection pass prepared this
                        # exact immutable mesh table with its explicit body count.
                        body, count = 'nullptr', '0U'
                    if not body or not count: raise ValueError(name + ': mesh bounds missing')
                    value = f'execution->translated_meshes({variable}, {body}, {count}, {lookup.get("mesh_capacity", "0U")})'
                else: value = f'execution->address({variable})'
            elif typ.get('scalarType') == 'bool': value = f'std::uint32_t({variable})'
            else:
                lines.append(f'static_assert(sizeof({variable}) == {length}U);')
            lines.extend([f'const auto value_{offset} = {value};',
                          f'std::memcpy(constants.data() + {offset}, &value_{offset}, {length});'])
        for p, variable in zip(reflected, names): pack(p, variable)
        gx, gy, gz = entry['threadGroupSize']
        lines += [f'execution->dispatch("{args.module}", "{name}", shader_code, grid, block, dim3{{{gx}, {gy}, {gz}}}, constants);', '}']
        header += lines
    header.append('} // namespace')
    wrapper = pathlib.Path(args.wrapper).read_text()
    wrapper = re.sub(r'#include "parallel_mater_\w+_runtime.cu"', '\n'.join(header), wrapper)
    # Vulkan has no cooperative grid barrier. The shared solver already has a
    # one-workgroup path; request exactly that path from the shared scheduler.
    if args.module == 'geometry_constraints':
        wrapper = re.sub(r'return device::from_driver_error\(cudaOccupancyMaxActiveBlocksPerMultiprocessor\([^;]+;',
                         'if (!resident_blocks || !block_size) return PM_ERROR_INVALID_ARGUMENT;\n    *resident_blocks = 1; return PM_SUCCESS;', wrapper)
        start = wrapper.index('    void *arguments[]')
        end = wrapper.index('\n}', start)
        wrapper = wrapper[:start] + '    return PM_ERROR_FEATURE_NOT_PRESENT;' + wrapper[end:]
    def launch(match):
        kernel, config = match.groups()
        fields = split_args(config)
        if len(fields) != 4 or kernel not in entries: raise ValueError('Unknown launch ' + kernel)
        return f'vk_{kernel}({fields[3]}, dim3({fields[0]}), dim3({fields[1]}), '
    wrapper = re.sub(r'(\w+)<<<(.*?)>>>\(\s*', launch, wrapper, flags=re.S)
    if '<<<' in wrapper or 'cudaLaunchCooperative' in wrapper: raise ValueError('Unconverted launch')
    pathlib.Path(args.output).write_text(wrapper)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('cuda', 'spirv', 'reflection', 'wrapper', 'module', 'output'):
        parser.add_argument('--' + name, required=True)
    generate(parser.parse_args())
