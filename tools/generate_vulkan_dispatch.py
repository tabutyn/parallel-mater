"""Generate transport bindings, never physics, from Slang's reflected ABI.

Slang reflection supplies storage types, source argument order and constant
layouts. Handwritten legacy wrappers supply launch geometry until their separate
migration to the common command-list API. No generated CUDA is consumed.
Unsupported syntax or layout changes fail the build instead of guessing.
"""
import argparse
import json
import pathlib
import re
import struct

from slang_abi import ReflectedABI


def split_args(text):
    result, begin, depth = [], 0, 0
    for i, c in enumerate(text):
        if c in '(<[': depth += 1
        elif c in ')>]': depth -= 1
        elif c == ',' and depth == 0:
            result.append(text[begin:i].strip()); begin = i + 1
    result.append(text[begin:].strip())
    return result


def generate(args):
    reflection = json.loads(pathlib.Path(args.reflection).read_text())
    abi = ReflectedABI(reflection)
    entries = abi.entries
    header = ['// Generated by generate_vulkan_dispatch.py; do not edit.',
              '#include "driver/vulkan/schedule_context.hpp"', 'namespace {']
    header += abi.declarations()
    shader = pathlib.Path(args.spirv).read_bytes()
    words = struct.unpack('<' + 'I' * (len(shader) // 4), shader)
    header.append('alignas(4) constexpr std::uint32_t shader_code[]{' + ','.join(hex(w) for w in words) + '};')
    for name, entry in entries.items():
        reflected = abi.parameters(entry)
        size = max((p['binding']['offset'] + p['binding']['size'] for p in reflected), default=4)
        names = ['arg_' + p['name'] for p in reflected]
        lookup = {p['name']: n for p, n in zip(reflected, names)}
        lines = [f'void vk_{name}(cudaStream_t stream, dim3 grid, dim3 block, {abi.signature(entry)}) {{',
                 'auto *execution = parallel_mater::vulkan::context(stream);',
                 'if (!execution) return;', f'std::array<std::byte, {(size+3)&~3}> constants{{}};']
        if name == 'pm_evaluate_rigid_leaf_pairs': lines.append('block.x = 8U;')
        if name in ('pm_reduce_rigid_leaf_manifolds', 'pm_finalize_rigid_contact_manifolds',
                    'pm_load_rigid_contact_cache', 'pm_save_rigid_contact_cache'):
            # These kernels assign one pair per thread, unlike the cooperative
            # leaf kernels. Avoid launching mostly inactive workgroups: Mali
            # reserves private scratch even for threads that immediately return.
            count = lookup.get('body_count', lookup.get('count'))
            if not count: raise ValueError(name + ': pair bounds missing')
            lines.append(f'grid.x = static_cast<unsigned>(std::min<std::uint64_t>(grid.x, '
                         f'(std::uint64_t({count}) * {count} + block.x - 1U) / block.x));')
        def pack(p, variable, base=0):
            binding, typ = p['binding'], p['type']
            typ = abi.resolve(typ)
            offset, length = base + binding['offset'], binding['size']
            value = variable
            if typ['kind'] == 'struct':
                for field in typ['fields']:
                    pack(field, f'{variable}.{field["name"]}', offset)
                return
            elif typ['kind'] == 'array':
                stride = typ['uniformStride']
                for i in range(typ['elementCount']):
                    pack({'type': typ['elementType'],
                          'binding': {'offset': i * stride, 'size': stride}},
                         f'{variable}.data[{i}]', offset)
                return
            elif typ['kind'] == 'pointer':
                pointee = typ['valueType']
                pointee = pointee if isinstance(pointee, str) else pointee.get('name')
                if pointee == 'TriangleMeshResource':
                    body = lookup.get('parameters', lookup.get('body_parameters'))
                    count = lookup.get('body_count', lookup.get('count'))
                    count_type = next((x['type']['kind'] for x in reflected if x['name'] == 'count'), None)
                    if 'body_count' not in lookup and count_type == 'pointer': count = None
                    if 'body_index' in lookup: count = f'({lookup["body_index"]} + 1U)'
                    if name == 'fluid_resolve_moving_contacts':
                        # The immediately preceding detection pass prepared this
                        # exact immutable mesh table with its explicit body count.
                        body, count = 'nullptr', '0U'
                    if not body or not count: raise ValueError(name + ': mesh bounds missing')
                    value = f'execution->translated_meshes({variable}, {body}, {count}, {lookup.get("mesh_capacity", "0U")})'
                else: value = f'execution->address({variable})'
            elif typ.get('scalarType') == 'bool': value = f'std::uint32_t({variable})'
            else:
                lines.append(f'static_assert(sizeof({variable}) == {length}U);')
            lines.extend([f'const auto value_{offset} = {value};',
                          f'std::memcpy(constants.data() + {offset}, &value_{offset}, {length});'])
        for p, variable in zip(reflected, names): pack(p, variable)
        gx, gy, gz = entry['threadGroupSize']
        lines += [f'execution->dispatch("{args.module}", "{name}", shader_code, grid, block, dim3{{{gx}, {gy}, {gz}}}, constants);', '}']
        header += lines
    header.append('} // namespace')
    wrapper = abi.normalize_legacy_wrapper(pathlib.Path(args.wrapper).read_text())
    wrapper = re.sub(r'#include "parallel_mater_\w+_runtime.cu"', '\n'.join(header), wrapper)
    # Vulkan has no cooperative grid barrier. The shared solver already has a
    # one-workgroup path; request exactly that path from the shared scheduler.
    if args.module == 'geometry_constraints':
        wrapper = re.sub(r'return device::from_driver_error\(cudaOccupancyMaxActiveBlocksPerMultiprocessor\([^;]+;',
                         'if (!resident_blocks || !block_size) return PM_ERROR_INVALID_ARGUMENT;\n    *resident_blocks = 1; return PM_SUCCESS;', wrapper)
        start = wrapper.index('    void *arguments[]')
        end = wrapper.index('\n}', start)
        wrapper = wrapper[:start] + '    return PM_ERROR_FEATURE_NOT_PRESENT;' + wrapper[end:]
    def launch(match):
        kernel, config = match.groups()
        fields = split_args(config)
        if len(fields) != 4 or kernel not in entries: raise ValueError('Unknown launch ' + kernel)
        return f'vk_{kernel}({fields[3]}, dim3({fields[0]}), dim3({fields[1]}), '
    wrapper = re.sub(r'(\w+)<<<(.*?)>>>\(\s*', launch, wrapper, flags=re.S)
    if '<<<' in wrapper or 'cudaLaunchCooperative' in wrapper: raise ValueError('Unconverted launch')
    pathlib.Path(args.output).write_text(wrapper)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('spirv', 'reflection', 'wrapper', 'module', 'output'):
        parser.add_argument('--' + name, required=True)
    generate(parser.parse_args())
